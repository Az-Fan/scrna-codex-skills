suppressPackageStartupMessages({library(Seurat);library(jsonlite)})
source('toolkit/R/runtime.R');source('toolkit/R/umap_review.R')
set.seed(7)
counts<-matrix(rpois(8*60,3),8,60,dimnames=list(paste0('g',1:8),paste0('c',1:60)))
obj<-CreateSeuratObject(counts)
obj$sample<-rep(paste0('s',1:6),each=10)
obj$cluster<-c(rep('2',20),rep('10',40))
xy<-matrix(rnorm(120),ncol=2,dimnames=list(colnames(obj),c('UMAP_1','UMAP_2')))
obj[['umap']]<-CreateDimReducObject(embeddings=xy,key='UMAP_',assay='RNA')
original<-serialize(obj,NULL)
root<-tempfile('umap-review-');dir.create(root)
for(fmt in c('pdf','png')) {
 out<-file.path(root,fmt);dir.create(out)
 cfg<-list(metadata=list(sample='sample',cluster='cluster',reduction='umap'),output=list(figure_format=fmt))
 rng<-.Random.seed
 files<-review_cluster_umap(obj,cfg,out)
 stopifnot(identical(rng,.Random.seed))
 stopifnot(all(file.exists(files)),identical(serialize(obj,NULL),original))
 tab<-read.delim(file.path(out,'sample_cluster_counts.tsv'))
 stopifnot(nrow(tab)==12,sum(tab$cells)==60,any(tab$cells==0),all(abs(tapply(tab$sample_fraction,tab$sample,sum)-1)<1e-10),all(abs(tapply(tab$cluster_fraction,tab$cluster,sum)-1)<1e-10))
 info<-read_json(file.path(out,'_provenance/umap_review_methods.json'),simplifyVector=TRUE)
 stopifnot(info$sample_pages==2,identical(info$clusters,c('2','10')),isTRUE(all.equal(info$shared_xlim,unname(range(xy[,1])),tolerance=1e-12)))
 if(fmt=='pdf') {
  text<-paste(rawToChar(readBin(file.path(out,'sample_highlights.pdf'),'raw',n=1e7),multiple=TRUE),collapse='')
  stopifnot(length(gregexpr('/Type /Page\\b',text,perl=TRUE,useBytes=TRUE)[[1]])==2,length(list.files(out,pattern='[.]png$'))==0)
 } else stopifnot(length(list.files(out,pattern='[.]pdf$'))==0,length(list.files(out,pattern='[.]png$'))==3)
 bad<-cfg;bad$review_umap<-list(cluster_colors=list('2'='red','10'='#FF0000'))
 stopifnot(inherits(try(review_cluster_umap(obj,bad,out),silent=TRUE),'try-error'))
 partial<-obj;partial[['umap']]@cell.embeddings<-xy[-1,,drop=FALSE]
 stopifnot(inherits(try(review_cluster_umap(partial,cfg,out),silent=TRUE),'try-error'))
 bad<-cfg;bad$review_umap<-list(sample_order=c('s1','s2'))
 stopifnot(inherits(try(review_cluster_umap(obj,bad,out),silent=TRUE),'try-error'))
}
cat('PASS shared-coordinate UMAP review, complete counts/fractions, numeric ordering, multipage PDF, single-format PNG, palette validation and unchanged object\n')
